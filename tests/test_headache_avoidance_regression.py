    "머리가 늘 아파",
    "두통약 먹었어",
    "평생 두통을 달고 살았어요",
    "평생 두통약을 먹고 살아요",
    "난생 처음 두통약을 먹어 봤어요",
    "평생 두통 없이 살았어요",
    "생전 두통약 모르고 살았어요",
    # A-1: 지시어 없이 "적이 없다"는 아픈 적이 없다는 말이다
    "살면서 머리가 아파본 적이 없어요",
    "살면서 이런 두통약은 먹어본 적이 없어요",
    "이런 두통은 없었으면 좋겠어요",
    # A-1: 심함 낱말 없는 "제일·가장"
    "살면서 제일 좋았던 건 두통이 없던 때예요",
    "평생 가장 힘든 건 남편 두통 수발이었어요",
