"""말을 피하는 대답 감지 (11/12).

11/11 실기기 시험에서 "말하지 않고 있어…", "너무 힘들어서 얘기를 못 하겠어"에 말벗이 질문 주제를 갖다 붙이거나 더 캐물었다.
DGX 시험(11/12, 서버 e06c15f·int8·cc7): 피하는 말 40개 가운데 30개가 '대답과 무관'에 걸려 "조금 더 들려주실 수 있을까요?"로
나갔고(더 말하라고 캐묻게 됨), cc7 대답도 대부분 "특별히 걱정되는 일이 있으신가요?"로 캐물었다.

정규식 측정(DGX): 피하는 말 39/40, 아닌 말 0/20, CareCall 어르신 대답 0.12%(대부분 "근데 왜 자꾸 물어봐요?" 정탐).
'소용없' 단독과 '안 했'은 오탐(…"별 얘기 안 했는데")이라 뺐다. "말하지 않고 있어"는 이 저장소에서 한 줄 더했다(측정 밖).
몸이 불편해 말을 못 하는 말("숨이 차서 말을 못하겠네")은 응급일 수 있어 피하는 말로 보지 않는다 - 평소 경로(위험 판정)로 간다.

11/12 기능 점검(AI #273) 반영:
  H-1 몸 증상 제외를 넓힘 - "혀가 굳어서·입이 안 돌아가서·쓰러질 것 같아서·기운이 없어서 말을 못 하겠어"는
      뇌졸중·쓰러짐일 수 있는데 낱말 위험 규칙에 안 걸려, 물러나는 문장과 조기 종료로 빠졌다
  M-1 남 이야기를 뺌 - "손주가 말하지 않고 있어서 걱정이야"·"영감이 말하기 싫다고" (가족 주어·전해 들은 말투)
      "말하지 않고 있어"는 문장 끝일 때만 본다
  L-1 흔한 표현 더함 - "그만 물어봐"·"대답하기 싫어"·"몰라 묻지 마요"·"할 얘기 없어"
  (DGX CareCall 어르신 대답 전체로 바꾸기 전후 감지를 대 봤다 - PR 본문)
"""
from __future__ import annotations

import re

AVOID_PATTERN = re.compile(
    r"(말|얘기|이야기)(는|은|도|을|를)?\s?(하기|하고|해|할|꺼내기|떼기)?\s?"
    r"(싫|안\s?(할|하련|할란|하고)|못\s?하겠|하고\s?싶지\s?않|싶지\s?않|할\s?기분이\s?아니|하지\s?말자|좀\s?그렇|기도\s?(귀찮|힘들))"
    r"|(입|말)\s?(떼기|꺼내기)도"
    r"|묻지\s?(마|말어|말아)(라|요)?[.!~]*$"
    r"|물어보지\s?마|왜\s?자꾸\s?물어"
    r"|말해\s?(봤자|봐야|뭐해)|얘기해\s?봐야\s?소용없"
    r"|할\s?(말|얘기|이야기)\s?없(어|다|어요)$"
    r"|냅둬|고마해|말\s?할\s?힘"
    r"|나중에\s?(하자|얘기|기분)|다음에\s?얘기|그냥\s?넘어가자|묻어\s?두|몰라도\s?돼|혼자\s?삭이"
    r"|말하(면|고\s?나면)\s?(더|길어|후회)"
    r"|말도\s?마$|신경\s?쓰지\s?마$|아무\s?말도|몰라\s?그냥\s?그래$"
    r"|말\s?하지\s?않(을래|을게|고\s?있(?!어서|으니|는데))"  # 11/11 실기기 "말하지 않고 있어…" - '있어서'(남 이야기)는 뺌 (M-1)
    r"|그만\s?(물어|묻)|대답\s?(하기\s?)?싫"  # L-1
)
# 몸이 불편해 말을 못 하는 경우: 피하는 말이 아니라 응급일 수 있다
BODY_DISTRESS = re.compile(
    r"숨|가슴|목이|아파|아퍼|아프|어지러|토할|열이"
    r"|혀|입이|발음|마비|저려|저린|저리고|저리다|쓰러|기운|힘이\s?없|몸이|정신이"  # H-1: 뇌졸중 말하기 장애·쓰러짐·기력 저하
)
# 남 이야기: 가족·지인이 주어이거나 전해 들은 말투면 어르신 본인이 말을 피하는 것이 아니다 (M-1)
OTHER_PERSON = re.compile(
    r"(아들|딸|손주|손자|손녀|영감|할아버지|할머니|남편|아내|마누라|며느리|사위|자식|애들|친구|이웃|동생|언니|누나|오빠|형)"
    r"(이|가|는|은|도|들이|들은)\s?"
    r"|싫(대|다고|다며|다네|댔|어해|어하)|않(는대|대|다고|다며)"
)
_TRAILING = re.compile(r"[\s.…~!?]+$")


def is_avoidance(transcript: str) -> bool:
    """어르신이 말을 피하는 대답인가. 몸이 불편하다는 말이나 남 이야기면 아니다."""
    text = _TRAILING.sub("", transcript)  # 끝의 문장부호를 떼고 본다 ("할 말 없어…"의 $ 비교)
    if not text or BODY_DISTRESS.search(text) or OTHER_PERSON.search(text):
        return False
    return bool(AVOID_PATTERN.search(text))
