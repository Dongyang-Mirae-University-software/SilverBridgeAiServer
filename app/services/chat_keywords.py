    r"물(을|은|도)?[^.!?。]{0,8}(마시|마셔|드시|드셔)|물몇잔|수분|낮잠|잠을|잠은|몇시간자|몇시간주무|수면|"
    r"더위|폭염|열사병|추위|한파|난방|치매|기억력|깜빡깜빡"
